"""Build docs/models.md (US-15.4 / US-16.4) from services/artifacts/{ml,dl,qml}/metadata.json and check NFR-A1.
   python scripts/make_models_md.py"""
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..")
TARGET = {"ml": 70.0, "dl": 70.0, "qml": 60.0}          # NFR-A1
NAMES = {"ml": "ML", "dl": "DL", "qml": "QML"}

rows, notes = [], []
for key in ("ml", "dl", "qml"):
    p = os.path.join(ROOT, "services", "artifacts", key, "metadata.json")
    if not os.path.exists(p):
        rows.append(f"| {NAMES[key]} | (not trained) | | | | | | | |")
        notes.append(f"- {NAMES[key]}: no metadata.json yet - train it (see services/README.md).")
        continue
    m = json.load(open(p))
    t, b = m.get("test_metrics", {}), m.get("baseline_test_metrics", {})
    acc = t.get("accuracy")
    ok = acc is not None and acc >= TARGET[key]
    rows.append(f"| {NAMES[key]} | {m.get('algorithm')} | {m.get('version')} | {acc}% | {t.get('macro_f1')} | {b.get('accuracy')}% | "
                f"{m.get('n_train')} / {m.get('n_test')} | {TARGET[key]:.0f}% | {'PASS' if ok else 'SHORTFALL'} |")
    if not ok:
        notes.append(f"- {NAMES[key]}: {acc}% < {TARGET[key]:.0f}% -> record as a deviation (TBD-1) in docs/deviations.md.")
    if key == "qml":
        notes.append(f"- QML: {m.get('algorithm')}; readout: {m.get('readout')}; PCA variance kept: {m.get('pca_explained_variance')} (TBD-2).")

out = f"""# Model results (generated by scripts/make_models_md.py)

Held-out test = last 3 months of the data. Baseline = "tomorrow has yesterday's class".

| Model | Algorithm | Version | Test accuracy | Macro-F1 | Baseline acc. | n_train / n_test | NFR-A1 target | Result |
|---|---|---|---|---|---|---|---|---|
""" + "\n".join(rows) + """

## Notes
""" + ("\n".join(notes) or "- all targets met") + """

## Final algorithm choices (TBD-3)
- ML: RF vs XGBoost -> see "Algorithm" column (best on validation).
- DL: LSTM vs MLP -> see "Algorithm" column.
- QML: qubit count and ansatz -> see the QML note above (TBD-2).
"""
open(os.path.join(ROOT, "docs", "models.md"), "w").write(out)
print("docs/models.md written")
