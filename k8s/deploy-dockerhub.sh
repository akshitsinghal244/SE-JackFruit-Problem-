#!/usr/bin/env bash
# Deploy the images that CD pushed to DockerHub (US-25/US-27).
#   ./k8s/deploy-dockerhub.sh <dockerhub-user> [tag=latest]
set -euo pipefail
cd "$(dirname "$0")/.."
USER_=${1:?usage: deploy-dockerhub.sh <dockerhub-user> [tag]}; TAG=${2:-latest}
OVL=k8s/overlays/dockerhub; mkdir -p $OVL
{
  echo "# generated by deploy-dockerhub.sh - do not edit"
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"; echo "kind: Kustomization"; echo "resources: [../../base]"; echo "images:"
  for p in "gateway gateway" "client client" "ml ml" "dl dl" "qml qml"; do set -- $p
    echo "  - { name: rdcp-$1, newName: $USER_/rdcp-$2, newTag: \"$TAG\" }"
  done
} > $OVL/kustomization.yaml
# base uses images named rdcp-<svc>:1.0 -> rewrite matches by name
source "$(dirname "$0")/common.sh"; create_secret; apply_and_wait $OVL
